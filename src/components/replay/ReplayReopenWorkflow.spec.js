import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import Detail from './ReplayReopenAppealDetail.vue'
import Assignment from './ReplayReopenAssignment.vue'
import Policies from './ReplayReopenPolicies.vue'
import * as api from '../../api/replayReopens.js'
import { searchReplayIssueUsers } from '../../api/replayIssues.js'
vi.mock('../../api/replayReopens.js', () => ({ getReopenAppeal: vi.fn(), decideReopenAppeal: vi.fn(), withdrawReopenAppeal: vi.fn(), reassignReopenAppeal: vi.fn(), assignReopenEvent: vi.fn(), getReopenPolicies: vi.fn(), saveReopenPolicy: vi.fn(), searchReopenDevelopers: vi.fn() }))
vi.mock('../../api/replayIssues.js', () => ({ searchReplayIssueUsers: vi.fn() }))
const appeal = { id: 3, version: 6, status: 'PENDING', issueDomain: '结算组', suggestedOwnerUsername: 'liu', suggestedOwnerName: '刘洋', reason: '申请原因', evidence: '日志', items: [{ eventId: 7, issueKey: 'KEY', occurrenceNo: 1, batchName: 'RPT-1' }], canDecide: true, canWithdraw: false, canReassign: false }
beforeEach(() => {
  vi.resetAllMocks()
  api.getReopenAppeal.mockResolvedValue({ ...appeal })
  api.searchReopenDevelopers.mockResolvedValue([{ username: 'liu', realName: '刘洋' }, { username: 'chen', realName: '陈浩' }])
  searchReplayIssueUsers.mockResolvedValue([{ username: 'lin', realName: '林悦' }, { username: 'zhao', realName: '赵宁' }])
})
describe('reopen workflow forms', () => {
  it('requires explicit final owner and allows a different developer than suggested', async () => {
    const w = mount(Detail, { props: { appealId: 3 } }); await flushPromises()
    expect(w.get('[data-testid="final-owner"] select').element.value).toBe('')
    await w.get('[data-testid="decision-reason"]').setValue('核查由陈浩维护')
    expect(w.get('[data-testid="approve-adjustment"]').attributes('disabled')).toBeDefined()
    await w.get('[data-testid="final-owner"] select').setValue('chen')
    api.decideReopenAppeal.mockRejectedValueOnce(new Error('权限已变化'))
    await w.get('[data-testid="approve-adjustment"]').trigger('click'); await flushPromises()
    expect(api.decideReopenAppeal).toHaveBeenCalledWith(3, { expectedVersion: 6, decision: 'APPROVE', finalOwnerUsername: 'chen', reason: '核查由陈浩维护' })
    expect(w.get('[data-testid="decision-reason"]').element.value).toBe('核查由陈浩维护')
    api.decideReopenAppeal.mockResolvedValueOnce({ ...appeal, status: 'INVALID', canDecide: false })
    await w.get('[data-testid="approve-adjustment"]').trigger('click'); await flushPromises()
    expect(w.text()).toContain('已失效')
    expect(w.find('[data-testid="approve-adjustment"]').exists()).toBe(false)
    expect(w.emitted('changed')).toHaveLength(1)
    w.unmount()
  })
  it('uses capability flags for withdrawal and sends fresh version and reason', async () => {
    api.getReopenAppeal.mockResolvedValue({ ...appeal, canDecide: false, canWithdraw: true })
    const w = mount(Detail, { props: { appealId: 3 } }); await flushPromises()
    expect(w.find('[data-testid="approve-adjustment"]').exists()).toBe(false)
    await w.get('[data-testid="withdraw-reason"]').setValue('补充证据')
    api.withdrawReopenAppeal.mockResolvedValue({ ...appeal, status: 'WITHDRAWN', canDecide: false, canWithdraw: false })
    await w.get('[data-testid="withdraw-adjustment"]').trigger('click'); await flushPromises()
    expect(api.withdrawReopenAppeal).toHaveBeenCalledWith(3, { expectedVersion: 6, reason: '补充证据' })
    w.unmount()
  })
  it('limits admin reassignment to the configured leaders and requires a reason', async () => {
    api.getReopenAppeal.mockResolvedValue({ ...appeal, canDecide: false, canReassign: true })
    const w = mount(Detail, { props: { appealId: 3, policies: [{ issueDomain: '结算组', leaderUsernames: ['lin', 'zhao'] }] } }); await flushPromises()
    await w.get('[data-testid="reassign-leader"]').setValue('zhao')
    await w.get('[data-testid="reassign-reason"]').setValue('原领导离岗')
    api.reassignReopenAppeal.mockResolvedValue({ ...appeal, leaderUsername: 'zhao', canDecide: false, canReassign: true })
    await w.get('[data-testid="reassign-adjustment"]').trigger('click'); await flushPromises()
    expect(api.reassignReopenAppeal).toHaveBeenCalledWith(3, { expectedVersion: 6, leaderUsername: 'zhao', reason: '原领导离岗' })
    w.unmount()
  })
  it('assigns an unassigned event only with server capability and explicit developer', async () => {
    const w = mount(Assignment, { props: { item: { event: { id: 7, version: 4 }, canAssign: true } } }); await flushPromises()
    await w.get('[data-testid="assignment-owner"] select').setValue('chen')
    await w.get('[data-testid="assignment-reason"]').setValue('核实本次维护记录')
    api.assignReopenEvent.mockResolvedValue({})
    await w.get('form').trigger('submit'); await flushPromises()
    expect(api.assignReopenEvent).toHaveBeenCalledWith(7, { expectedVersion: 4, targetOwnerUsername: 'chen', reason: '核实本次维护记录' })
    expect(w.emitted('changed')).toHaveLength(1)
    w.unmount()
  })
  it('loads and saves policies with chosen leaders, primary, version and reason', async () => {
    api.getReopenPolicies.mockResolvedValue([{ issueDomain: '结算组', leaderUsernames: ['lin'], primaryLeaderUsername: 'lin', version: 4 }])
    const w = mount(Policies, { props: { domains: ['结算组', '贷款组'] } }); await flushPromises()
    await w.get('[data-testid="policy-domain"]').setValue('结算组')
    await w.get('[data-testid="policy-user"] select').setValue('zhao')
    await w.get('[data-testid="add-policy-leader"]').trigger('click')
    await w.get('[data-testid="policy-primary"]').setValue('zhao')
    await w.get('[data-testid="policy-reason"]').setValue('配置审批领导')
    api.saveReopenPolicy.mockRejectedValueOnce(new Error('版本冲突'))
    await w.get('form').trigger('submit'); await flushPromises()
    expect(api.saveReopenPolicy).toHaveBeenCalledWith('结算组', { expectedVersion: 4, leaderUsernames: ['lin', 'zhao'], primaryLeaderUsername: 'zhao', reason: '配置审批领导' })
    expect(w.get('[data-testid="policy-reason"]').element.value).toBe('配置审批领导')
    w.unmount()
  })
  it('permits revoking all policy leaders with explicit reason and empty primary', async () => {
    api.getReopenPolicies.mockResolvedValue([{ issueDomain: '结算组', leaderUsernames: ['lin'], primaryLeaderUsername: 'lin', version: 4 }])
    const w = mount(Policies, { props: { domains: ['结算组'] } }); await flushPromises()
    await w.get('[data-testid="policy-domain"]').setValue('结算组')
    await w.get('[aria-label="移除 lin"]').trigger('click')
    await w.get('[data-testid="policy-reason"]').setValue('撤销领域审批授权')
    api.saveReopenPolicy.mockResolvedValue({ issueDomain: '结算组', leaderUsernames: [], primaryLeaderUsername: '', version: 5 })
    await w.get('form').trigger('submit'); await flushPromises()
    expect(api.saveReopenPolicy).toHaveBeenCalledWith('结算组', { expectedVersion: 4, leaderUsernames: [], primaryLeaderUsername: '', reason: '撤销领域审批授权' })
    expect(w.emitted('changed')).toHaveLength(1)
    w.unmount()
  })

  it('waits for delayed policies before initializing an existing domain draft', async () => {
    let resolvePolicies
    api.getReopenPolicies.mockReturnValueOnce(new Promise(resolve => { resolvePolicies = resolve }))
    const w = mount(Policies, { props: { domains: ['结算组'] } }); await flushPromises()
    expect(w.get('[data-testid="policy-domain"]').attributes('disabled')).toBeDefined()
    expect(w.find('[data-testid="policy-primary"]').exists()).toBe(false)
    resolvePolicies([{ issueDomain: '结算组', leaderUsernames: ['lin'], primaryLeaderUsername: 'lin', version: 8 }])
    await flushPromises()
    expect(w.get('[data-testid="policy-domain"]').attributes('disabled')).toBeUndefined()
    await w.get('[data-testid="policy-domain"]').setValue('结算组')
    expect(w.get('[data-testid="policy-primary"]').element.value).toBe('lin')
    await w.get('[data-testid="policy-reason"]').setValue('确认现有授权')
    api.saveReopenPolicy.mockResolvedValueOnce({ issueDomain: '结算组', leaderUsernames: ['lin'], primaryLeaderUsername: 'lin', version: 9 })
    await w.get('form').trigger('submit'); await flushPromises()
    expect(api.saveReopenPolicy).toHaveBeenCalledWith('结算组', { expectedVersion: 8, leaderUsernames: ['lin'], primaryLeaderUsername: 'lin', reason: '确认现有授权' })
    w.unmount()
  })

})
